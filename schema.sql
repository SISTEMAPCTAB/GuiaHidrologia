create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name,role_title,institution,municipality,phone,username)
 values(new.id,coalesce(new.raw_user_meta_data->>'full_name','Usuario'),new.raw_user_meta_data->>'role_title',new.raw_user_meta_data->>'institution',new.raw_user_meta_data->>'municipality',new.raw_user_meta_data->>'phone',coalesce(nullif(new.raw_user_meta_data->>'username',''),split_part(new.email,'@',1)||'_'||substr(new.id::text,1,6)))
 on conflict(id) do nothing;
 insert into public.course_progress(user_id) values(new.id) on conflict(user_id) do nothing; return new;
end $$;
