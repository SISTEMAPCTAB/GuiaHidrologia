create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select coalesce((select is_admin from public.profiles where id=auth.uid()),false)
$$;

create or replace function public.touch_last_access() returns void language plpgsql security definer set search_path=public as $$
begin if auth.uid() is null then raise exception 'authentication required'; end if; update public.profiles set last_access_at=now() where id=auth.uid(); end $$;

create or replace function public.complete_activity(input_module integer,input_activity text) returns jsonb language plpgsql security definer set search_path=public as $$
declare req_count int; done_count int; mods integer[];
begin
 if auth.uid() is null then raise exception 'authentication required'; end if;
 if not exists(select 1 from public.required_activities where module_index=input_module and activity_id=input_activity) then raise exception 'invalid activity'; end if;
 insert into public.activity_completions(user_id,module_index,activity_id) values(auth.uid(),input_module,input_activity) on conflict do nothing;
 select count(*) into req_count from public.required_activities where module_index=input_module;
 select count(*) into done_count from public.activity_completions where user_id=auth.uid() and module_index=input_module;
 if done_count>=req_count then
  update public.course_progress set completed_modules=(select array_agg(distinct x order by x) from unnest(completed_modules||input_module) x),updated_at=now() where user_id=auth.uid();
 end if;
 select completed_modules into mods from public.course_progress where user_id=auth.uid();
 return jsonb_build_object('completed_modules',coalesce(mods,'{}'::integer[]),'module_complete',done_count>=req_count,'completed_activities',done_count,'required_activities',req_count);
end $$;

create or replace function public.admin_dashboard() returns table(
 user_id uuid,full_name text,institution text,municipality text,email text,created_at timestamptz,last_access_at timestamptz,
 completed_modules integer[],completed_count integer,progress_pct integer,attempt_count integer,latest_score integer,approved boolean,folio text,issued_at timestamptz
) language plpgsql security definer set search_path=public,auth as $$
begin
 if not public.is_admin() then raise exception 'forbidden'; end if;
 return query select p.id,p.full_name,p.institution,p.municipality,u.email,p.created_at,p.last_access_at,
  coalesce(cp.completed_modules,'{}'::integer[]),coalesce(cardinality(cp.completed_modules),0),round(coalesce(cardinality(cp.completed_modules),0)*100.0/18)::int,
  coalesce(ea.cnt,0)::int,ea.latest_score,coalesce(ea.ever_approved,false),c.folio,c.issued_at
 from public.profiles p join auth.users u on u.id=p.id left join public.course_progress cp on cp.user_id=p.id
 left join lateral(select count(*) cnt,(array_agg(e.score order by e.created_at desc))[1] latest_score,bool_or(e.approved) ever_approved from public.exam_attempts e where e.user_id=p.id) ea on true
 left join public.certificates c on c.user_id=p.id and c.course_code='AMH-HID-2026'
 where p.is_admin=false order by p.created_at desc;
end $$;

create or replace function public.admin_participant_detail(input_user uuid) returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare result jsonb;
begin
 if not public.is_admin() then raise exception 'forbidden'; end if;
 select jsonb_build_object(
  'profile',jsonb_build_object('id',p.id,'full_name',p.full_name,'institution',p.institution,'municipality',p.municipality,'email',u.email,'created_at',p.created_at,'last_access_at',p.last_access_at),
  'completed_modules',coalesce(to_jsonb(cp.completed_modules),'[]'::jsonb),
  'activities',coalesce((select jsonb_agg(jsonb_build_object('module_index',a.module_index,'activity_id',a.activity_id,'completed_at',a.completed_at) order by a.module_index,a.completed_at) from public.activity_completions a where a.user_id=p.id),'[]'::jsonb),
  'attempts',coalesce((select jsonb_agg(jsonb_build_object('score',e.score,'correct_count',e.correct_count,'approved',e.approved,'created_at',e.created_at) order by e.created_at desc) from public.exam_attempts e where e.user_id=p.id),'[]'::jsonb),
  'certificate',(select to_jsonb(c) from public.certificates c where c.user_id=p.id and c.course_code='AMH-HID-2026')
 ) into result from public.profiles p join auth.users u on u.id=p.id left join public.course_progress cp on cp.user_id=p.id where p.id=input_user;
 return result;
end $$;

create or replace function public.verify_certificate(input_folio text) returns table(folio text,full_name text,course_code text,course_name text,score integer,issued_at timestamptz,valid boolean)
language sql stable security definer set search_path=public as $$
 select c.folio,p.full_name,c.course_code,'Guía Interactiva de Hidrología e Inundaciones de Tabasco'::text,c.score,c.issued_at,true
 from public.certificates c join public.profiles p on p.id=c.user_id where upper(c.folio)=upper(trim(input_folio))
$$;

